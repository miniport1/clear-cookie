import type { CookieDraft, CookieItem, ExportFormat, SameSiteStatus } from './types';

export interface ParseResult {
  format: ExportFormat;
  cookies: CookieDraft[];
  warnings: string[];
}

export function normalizeSameSite(raw: unknown): SameSiteStatus {
  if (typeof raw !== 'string') return 'unspecified';
  const v = raw.trim().toLowerCase();
  if (v === 'no_restriction' || v === 'none') return 'no_restriction';
  if (v === 'lax') return 'lax';
  if (v === 'strict') return 'strict';
  return 'unspecified';
}

export function normalizeExpiration(raw: unknown): number | undefined {
  if (typeof raw === 'number' && Number.isFinite(raw) && raw > 0) {
    // Convert millisecond timestamps to Unix seconds
    return raw > 1e11 ? Math.floor(raw / 1000) : Math.floor(raw);
  }
  if (typeof raw === 'string' && raw.trim() !== '') {
    const trimmed = raw.trim();
    const num = Number(trimmed);
    if (Number.isFinite(num)) {
      if (num <= 0) return undefined;
      return num > 1e11 ? Math.floor(num / 1000) : Math.floor(num);
    }
    const parsedDate = Date.parse(trimmed);
    if (!Number.isNaN(parsedDate) && parsedDate > 0) {
      return Math.floor(parsedDate / 1000);
    }
  }
  return undefined;
}

export function exportCookies(cookies: CookieItem[], format: ExportFormat): string {
  if (format === 'json') {
    const cleaned = cookies.map((c) => {
      const out: Record<string, unknown> = {
        name: c.name,
        value: c.value,
        domain: c.domain,
        hostOnly: c.hostOnly,
        path: c.path,
        secure: c.secure,
        httpOnly: c.httpOnly,
        sameSite: c.sameSite,
        session: c.session,
      };
      if (!c.session && typeof c.expirationDate === 'number') {
        out.expirationDate = c.expirationDate;
      }
      if (c.partitionKey && Object.keys(c.partitionKey).length > 0) {
        out.partitionKey = c.partitionKey;
      }
      return out;
    });
    return JSON.stringify(cleaned, null, 2);
  }

  if (format === 'header') {
    return cookies.map((c) => `${c.name}=${c.value}`).join('; ');
  }

  // Netscape HTTP Cookie File format
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by ClearCookie (offline local extension)',
    '',
  ];

  for (const c of cookies) {
    const includeSubdomains = !c.hostOnly && c.domain.startsWith('.');
    const domainField = c.httpOnly ? `#HttpOnly_${c.domain}` : c.domain;
    const flag = includeSubdomains ? 'TRUE' : 'FALSE';
    const pathField = c.path || '/';
    const secureField = c.secure ? 'TRUE' : 'FALSE';
    const expField = c.session || !c.expirationDate ? '0' : String(Math.floor(c.expirationDate));
    lines.push([domainField, flag, pathField, secureField, expField, c.name, c.value].join('\t'));
  }

  return lines.join('\n') + '\n';
}

export function detectFormat(raw: string): ExportFormat {
  const trimmed = raw.trim();
  if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
    return 'json';
  }
  const lines = trimmed.split(/\r?\n/);
  if (
    lines.some((line) => line.startsWith('# Netscape') || line.startsWith('# HTTP Cookie File')) ||
    lines.some((line) => {
      const stripped = line.startsWith('#HttpOnly_') ? line.slice('#HttpOnly_'.length) : line;
      return !stripped.startsWith('#') && stripped.split('\t').length >= 7;
    })
  ) {
    return 'netscape';
  }
  return 'header';
}

function getFallbackContext(fallbackUrl: string): { hostname: string; secure: boolean } {
  try {
    const parsed = new URL(fallbackUrl);
    return { hostname: parsed.hostname, secure: parsed.protocol === 'https:' };
  } catch {
    return { hostname: '', secure: false };
  }
}

function parseJsonCookies(raw: string, fallbackUrl: string): ParseResult {
  const warnings: string[] = [];
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error('JSON 格式无效，请检查括号或引号');
  }

  const list = Array.isArray(parsed) ? parsed : [parsed];
  const fallback = getFallbackContext(fallbackUrl);
  const cookies: CookieDraft[] = [];

  for (let i = 0; i < list.length; i++) {
    const item = list[i];
    if (!item || typeof item !== 'object') {
      warnings.push(`第 ${i + 1} 项不是有效的 Cookie 对象，已跳过`);
      continue;
    }
    const obj = item as Record<string, unknown>;
    const name = typeof obj.name === 'string' ? obj.name : '';
    if (!name) {
      warnings.push(`第 ${i + 1} 项缺少 name 字段，已跳过`);
      continue;
    }

    const value = typeof obj.value === 'string' ? obj.value : String(obj.value ?? '');
    const domain =
      typeof obj.domain === 'string' && obj.domain.trim() ? obj.domain.trim() : fallback.hostname;
    const path = typeof obj.path === 'string' && obj.path.trim() ? obj.path.trim() : '/';
    const sameSite = normalizeSameSite(obj.sameSite);
    const secure = Boolean(obj.secure) || sameSite === 'no_restriction';
    const httpOnly = Boolean(obj.httpOnly);
    const expirationDate = normalizeExpiration(obj.expirationDate ?? obj.expires);
    const session = typeof obj.session === 'boolean' ? obj.session : expirationDate === undefined;
    const hostOnly =
      typeof obj.hostOnly === 'boolean' ? obj.hostOnly : !domain.startsWith('.');

    const draft: CookieDraft = {
      name,
      value,
      domain,
      hostOnly,
      path,
      secure,
      httpOnly,
      sameSite,
      session,
      expirationDate: session ? undefined : expirationDate,
    };

    if (obj.partitionKey && typeof obj.partitionKey === 'object') {
      const pk = obj.partitionKey as Record<string, unknown>;
      if (typeof pk.topLevelSite === 'string') {
        draft.partitionKey = {
          topLevelSite: pk.topLevelSite,
          hasCrossSiteAncestor:
            typeof pk.hasCrossSiteAncestor === 'boolean' ? pk.hasCrossSiteAncestor : undefined,
        };
      }
    }

    cookies.push(draft);
  }

  return { format: 'json', cookies, warnings };
}

function parseNetscapeCookies(raw: string, fallbackUrl: string): ParseResult {
  const warnings: string[] = [];
  const cookies: CookieDraft[] = [];
  const fallback = getFallbackContext(fallbackUrl);
  const lines = raw.split(/\r?\n/);

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i]?.trim();
    if (!rawLine) continue;

    let httpOnly = false;
    let line = rawLine;
    if (line.startsWith('#HttpOnly_')) {
      httpOnly = true;
      line = line.slice('#HttpOnly_'.length);
    } else if (line.startsWith('#')) {
      continue;
    }

    const parts = line.split('\t');
    if (parts.length < 7) {
      warnings.push(`第 ${i + 1} 行列数不足 7 列，已跳过`);
      continue;
    }

    const [domainRaw, flagRaw, pathRaw, secureRaw, expRaw, name, ...valueRest] = parts;
    if (!name) {
      warnings.push(`第 ${i + 1} 行缺少名称，已跳过`);
      continue;
    }

    const domain = domainRaw?.trim() || fallback.hostname;
    const includeSubdomains = flagRaw?.trim().toUpperCase() === 'TRUE';
    const path = pathRaw?.trim() || '/';
    const secure = secureRaw?.trim().toUpperCase() === 'TRUE';
    const expirationDate = normalizeExpiration(expRaw);
    const session = expirationDate === undefined;
    const value = valueRest.join('\t');

    cookies.push({
      name,
      value,
      domain,
      hostOnly: !includeSubdomains,
      path,
      secure,
      httpOnly,
      sameSite: 'unspecified',
      session,
      expirationDate,
    });
  }

  return { format: 'netscape', cookies, warnings };
}

function parseHeaderCookies(raw: string, fallbackUrl: string): ParseResult {
  const warnings: string[] = [];
  const cookies: CookieDraft[] = [];
  const fallback = getFallbackContext(fallbackUrl);

  let cleaned = raw.trim();
  if (/^cookie\s*:/i.test(cleaned)) {
    cleaned = cleaned.replace(/^cookie\s*:/i, '').trim();
  }

  const pairs = cleaned.split(';');
  for (const part of pairs) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const eqIndex = trimmed.indexOf('=');
    if (eqIndex <= 0) {
      warnings.push(`已跳过无法解析的片段「${trimmed.slice(0, 24)}」`);
      continue;
    }
    const name = trimmed.slice(0, eqIndex).trim();
    const value = trimmed.slice(eqIndex + 1).trim();
    if (!name) continue;

    cookies.push({
      name,
      value,
      domain: fallback.hostname,
      hostOnly: true,
      path: '/',
      secure: fallback.secure,
      httpOnly: false,
      sameSite: 'unspecified',
      session: true,
    });
  }

  return { format: 'header', cookies, warnings };
}

export function parseCookies(
  raw: string,
  format: ExportFormat | 'auto',
  fallbackUrl: string,
): ParseResult {
  const trimmed = raw.trim();
  if (!trimmed) {
    throw new Error('内容为空，请先粘贴或选择文件');
  }
  const actualFormat = format === 'auto' ? detectFormat(trimmed) : format;
  if (actualFormat === 'json') return parseJsonCookies(trimmed, fallbackUrl);
  if (actualFormat === 'netscape') return parseNetscapeCookies(trimmed, fallbackUrl);
  return parseHeaderCookies(trimmed, fallbackUrl);
}
